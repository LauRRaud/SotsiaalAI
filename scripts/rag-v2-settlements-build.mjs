#!/usr/bin/env node
// ADR-103: the settlement units of Estonia and the municipality each lies in, for the chat's place reading.
// Source: the Land and Spatial Development Board's settlement units file (EHAK attributes), linked from
// https://geoportaal.maaamet.ee/est/ruumiandmed/haldus-ja-asustusjaotus-p119.html as asustusyksus_shp.zip. Only its
// attribute table (asustusyksus.dbf) is read: the unit's name and kind, and its municipality. The municipalities are
// matched by their display name with the app's own list (src/server/data/municipalities.rich.json), whose slugs give
// the region ids the chat uses.
// Usage: node scripts/rag-v2-settlements-build.mjs <asustusyksus.dbf> [--sha256 <of the zip>] [--check]
//   writes lib/rag-v2/adapters/settlement-data.js; --check only compares and exits 1 when the file would change.
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2), dbf = args.find(arg => !arg.startsWith('--')), check = args.includes('--check');
const sha = args.includes('--sha256') ? args[args.indexOf('--sha256') + 1] : null;
if (!dbf) { console.error('usage: rag-v2-settlements-build.mjs <asustusyksus.dbf> [--sha256 <zip sha256>] [--check]'); process.exit(2); }
const target = path.resolve('lib/rag-v2/adapters/settlement-data.js');

// dBase III: a 32-byte header, 32 bytes for each field up to 0x0D, then fixed-width records; the text is Windows-1257.
const buffer = fs.readFileSync(dbf), decoder = new TextDecoder('windows-1257');
const records = buffer.readUInt32LE(4), headerLength = buffer.readUInt16LE(8), recordLength = buffer.readUInt16LE(10), fields = [];
for (let at = 32; buffer[at] !== 0x0d; at += 32) fields.push({ name: buffer.toString('latin1', at, at + 11).replace(/\0.*$/u, ''), length: buffer[at + 16] });
for (const name of ['ANIMI', 'TYYP', 'ONIMI', 'EKSPORT']) if (!fields.some(field => field.name === name)) throw new Error(`field ${name} is missing from the table`);
const rows = [];
for (let index = 0; index < records; index++) {
  let at = headerLength + index * recordLength + 1; const row = {};
  for (const field of fields) { row[field.name] = decoder.decode(buffer.subarray(at, at + field.length)).trim(); at += field.length; }
  rows.push(row);
}
// EHAK kinds: 3 alev, 4 a town that is a municipality, 5 a town inside a municipality, 6 a town district, 7 alevik, 8 küla.
const KINDS = { 3: 'v', 4: 'l', 5: 'l', 6: 'o', 7: 'a', 8: 'k' }, KIND_WORD = /\s(küla|alevik|alev|linn|linnaosa)$/u;
const municipalities = JSON.parse(fs.readFileSync('src/server/data/municipalities.rich.json', 'utf8'));
const regionOf = new Map(municipalities.map(row => [row.displayName, row.slug.replaceAll('-', '_')]));
const byRegion = new Map(), unknown = new Set(), odd = [];
for (const row of rows) {
  const region = regionOf.get(row.ONIMI), kind = KINDS[row.TYYP];
  if (!region) { unknown.add(row.ONIMI); continue; }
  if (!kind) throw new Error(`unknown kind ${row.TYYP} of ${row.ANIMI}`);
  // A unit with a second official name is written "Riguldi küla / Rickul": both are its names.
  for (const written of row.ANIMI.split(' / ')) {
    const name = written.replace(KIND_WORD, '').trim();
    if (!name || /[:;|\s]/u.test(name)) { odd.push(written); continue; }
    byRegion.set(region, [...(byRegion.get(region) || []), `${name}:${kind}`]);
  }
}
if (unknown.size) throw new Error(`municipalities the app does not have: ${[...unknown].join(', ')}`);
const exported = [...new Set(rows.map(row => row.EKSPORT))];
if (exported.length !== 1 || !/^\d{8}$/u.test(exported[0])) throw new Error('the table has no single export date');
const date = `${exported[0].slice(0, 4)}-${exported[0].slice(4, 6)}-${exported[0].slice(6)}`;
const lines = [...byRegion.keys()].sort().map(region => `  ${region}: '${[...new Set(byRegion.get(region))].sort((a, b) => a.localeCompare(b, 'et')).join(';').replaceAll('\'', '\\\'')}',`);
const count = [...byRegion.values()].reduce((sum, list) => sum + new Set(list).size, 0);
const text = `// Generated by scripts/rag-v2-settlements-build.mjs. Do not edit: build it again from the source file.
// The settlement units of Estonia by municipality (ADR-103), from the Land and Spatial Development Board's settlement
// units file (EHAK attributes). Each unit is "Name:kind" with the kinds k (küla), a (alevik), v (alev), l (linn) and
// o (linnaosa); a unit with a second official name has an entry for each.
export const SETTLEMENT_SOURCE = Object.freeze({ file: 'asustusyksus_shp.zip', table: 'asustusyksus.dbf', exported: '${date}', ${sha ? `sha256: '${sha}', ` : ''}units: ${rows.length}, names: ${count} });
export const SETTLEMENTS = Object.freeze({
${lines.join('\n')}
});
`;
console.log(JSON.stringify({ units: rows.length, names: count, municipalities: byRegion.size, exported: date, left_out: odd }));
if (check) { const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8').replace(/\r\n/gu, '\n') === text; console.log(same ? 'unchanged' : 'would change'); process.exit(same ? 0 : 1); }
fs.writeFileSync(target, text);
console.log(`written ${path.relative(process.cwd(), target)} (${Buffer.byteLength(text)} bytes)`);
